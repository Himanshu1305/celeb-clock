#!/usr/bin/env node
/* Part AO — self-host fonts. Pulls only the weights the app uses, latin subset
 * (+ devanagari for Noto), as woff2, into public/fonts/, and writes src/styles/fonts.css
 * with local @font-face rules (font-display: swap). No runtime Google Fonts requests.
 */
import { mkdirSync, writeFileSync } from 'node:fs';

const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';
const OUT_DIR = 'public/fonts';
mkdirSync(OUT_DIR, { recursive: true });

const FAMILIES = [
  { css: 'Fraunces:ital,opsz,wght@0,9..144,500;0,9..144,600;0,9..144,700', family: 'Fraunces', weights: [500, 600, 700], subsets: ['latin'] },
  { css: 'Public+Sans:wght@400;500;600;700', family: 'Public Sans', weights: [400, 500, 600, 700], subsets: ['latin'] },
  { css: 'Noto+Sans+Devanagari:wght@400;600;700', family: 'Noto Sans Devanagari', weights: [400, 600, 700], subsets: ['devanagari', 'latin'] },
];

function slug(s) { return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''); }

// Split Google Fonts CSS into {subset, weight, url, unicodeRange} records.
function parseCss(css) {
  const out = [];
  // each block preceded by a /* subset */ comment
  const re = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*{([^}]+)}/gi;
  let m;
  while ((m = re.exec(css))) {
    const subset = m[1];
    const body = m[2];
    const weight = (body.match(/font-weight:\s*(\d+)/) || [])[1];
    const url = (body.match(/url\(([^)]+\.woff2)\)/) || [])[1];
    const unicodeRange = (body.match(/unicode-range:\s*([^;]+);/) || [])[1];
    if (url && weight) out.push({ subset, weight: Number(weight), url, unicodeRange: unicodeRange?.trim() });
  }
  return out;
}

let cssRules = [
  '/* Part AO — self-hosted fonts (generated by scripts/ao-fetch-fonts.mjs). Do not edit by hand. */',
  '',
];

for (const fam of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${fam.css}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`CSS fetch failed for ${fam.family}: ${res.status}`);
  const css = await res.text();
  const recs = parseCss(css).filter(r => fam.subsets.includes(r.subset) && fam.weights.includes(r.weight));
  // de-dup by (subset, weight)
  const seen = new Set();
  for (const r of recs) {
    const key = `${r.subset}-${r.weight}`;
    if (seen.has(key)) continue; seen.add(key);
    const fileName = `${slug(fam.family)}-${r.weight}-${r.subset}.woff2`;
    const fontRes = await fetch(r.url, { headers: { 'User-Agent': UA } });
    if (!fontRes.ok) throw new Error(`font fetch failed ${r.url}: ${fontRes.status}`);
    const buf = Buffer.from(await fontRes.arrayBuffer());
    writeFileSync(`${OUT_DIR}/${fileName}`, buf);
    cssRules.push(
      '@font-face {',
      `  font-family: '${fam.family}';`,
      '  font-style: normal;',
      `  font-weight: ${r.weight};`,
      '  font-display: swap;',
      `  src: url('/fonts/${fileName}') format('woff2');`,
      ...(r.unicodeRange ? [`  unicode-range: ${r.unicodeRange};`] : []),
      '}',
      '',
    );
    console.log(`saved ${fileName} (${(buf.length / 1024).toFixed(1)} KB)`);
  }
}

writeFileSync('src/styles/fonts.css', cssRules.join('\n'));
console.log('wrote src/styles/fonts.css');

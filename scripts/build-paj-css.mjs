// One-off: extract the shared design-system CSS from the finalized reference mockups
// and emit a SCOPED stylesheet (every selector prefixed under `.paj`) so the generic
// class names (.section/.btn/.field/.hero/.feature…) cannot leak into the other ~120
// site pages. The CSS block is identical across all four reference files, so vedic-final
// is used as the single source. Per-category accent overrides are appended at the end.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('docs/design-reference/vedic-final.html', 'utf8');
const css = src.slice(src.indexOf('<style>') + 7, src.indexOf('</style>'));

// Split a CSS string into top-level blocks by brace matching.
function splitBlocks(s) {
  const blocks = [];
  let depth = 0, start = 0;
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) { blocks.push(s.slice(start, i + 1)); start = i + 1; }
    }
  }
  const tail = s.slice(start).trim();
  if (tail) blocks.push(tail);
  return blocks;
}

function prefixSelector(sel) {
  sel = sel.trim();
  if (!sel) return sel;
  if (sel === ':root' || sel === 'body' || sel === 'html') return '.paj';
  if (sel.startsWith('body')) return '.paj' + sel.slice(4);
  if (sel.startsWith('html')) return '.paj' + sel.slice(4);
  if (sel === '*') return '.paj *';
  if (sel.startsWith('*')) return '.paj ' + sel;
  // The four design-variant classes (editorial/atlas/field-guide/workbench) live on the SAME
  // element as .paj (<div class="paj editorial">), not as a descendant — so they must attach
  // with NO space. Scoping them as a descendant ("\.paj .editorial") silently broke every
  // variant-specific layout rule (the editorial 2-col hero collapsed to a stacked white panel).
  for (const v of ['.editorial', '.atlas', '.field-guide', '.workbench']) {
    if (sel === v || sel.startsWith(v + ' ') || sel.startsWith(v + '.') || sel.startsWith(v + '[') || sel.startsWith(v + ':')) {
      return '.paj' + sel;
    }
  }
  return '.paj ' + sel;
}

// B12 — element-level COLOUR rules must never beat a utility/component class.
// `.paj h2{color:var(--navy)}` has specificity (0,1,1), which beats Tailwind's `text-white`
// (0,1,0): every legacy dark section rendered inside a PajPage shell got navy headings on a
// navy background (~1.1:1). For rules whose scoped selectors are purely element-level
// (`.paj h1`, `.paj a`, `.paj details>p`, `.paj summary:after` …), the `color` declaration is
// split out into a zero-specificity-scope rule — `:where(.paj) h2{color:…}` (0,0,1) — so an
// unstyled heading still gets navy (it still beats Tailwind preflight's bare element rules,
// because this sheet loads after index.css) but ANY class that sets a colour wins. Every
// other declaration keeps its original selector/specificity, so paj typography is unchanged.
const ELEMENT_ONLY = /^\.paj [a-z][a-z0-9]*(?:\s*>\s*[a-z][a-z0-9]*)*(?::{1,2}(?:before|after))?$/;
function isElementOnly(scopedSel) {
  return ELEMENT_ONLY.test(scopedSel.trim());
}
function splitColour(scopedSelectors, rest) {
  if (!scopedSelectors.every(isElementOnly)) return null;
  const body = rest.slice(1, rest.lastIndexOf('}'));
  const decls = body.split(';').map(d => d.trim()).filter(Boolean);
  const colour = decls.filter(d => /^color\s*:/i.test(d));
  if (!colour.length) return null;
  const other = decls.filter(d => !/^color\s*:/i.test(d));
  const whereSel = scopedSelectors.map(s => ':where(.paj) ' + s.trim().slice('.paj '.length)).join(',');
  const out = [];
  if (other.length) out.push(scopedSelectors.join(',') + '{' + other.join(';') + '}');
  out.push(whereSel + '{' + colour.join(';') + '}');
  return out.join('\n');
}
function scopeRule(selectors, rest) {
  const scoped = selectors.split(',').map(prefixSelector);
  return splitColour(scoped, rest) ?? scoped.join(',') + rest;
}

// Process a flat list of plain rules (no nested at-rules).
function processRules(body) {
  return splitBlocks(body).map(block => {
    const open = block.indexOf('{');
    if (open === -1) return block;
    return scopeRule(block.slice(0, open), block.slice(open));
  }).join('\n');
}

const out = [];
for (const block of splitBlocks(css)) {
  const b = block.trim();
  if (!b) continue;
  if (b.startsWith('@keyframes')) { out.push(b); continue; }
  if (b.startsWith('@media') || b.startsWith('@supports')) {
    const open = b.indexOf('{');
    const prelude = b.slice(0, open);
    const inner = b.slice(open + 1, b.lastIndexOf('}'));
    out.push(prelude + '{\n' + processRules(inner) + '\n}');
    continue;
  }
  // plain rule
  const open = b.indexOf('{');
  if (open === -1) { out.push(b); continue; }
  out.push(scopeRule(b.slice(0, open), b.slice(open)));
}

